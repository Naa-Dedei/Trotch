#!/usr/bin/env node
/**
 * Generates the DEMO network in two forms from scripts/demo-network.source.mjs:
 *   - src/data/demo-network.json  (bundled into the app as an offline/no-backend fallback)
 *   - supabase/seed.sql           (loaded by `supabase db reset` / pasted into the SQL editor)
 * IDs are deterministic UUIDs derived from the human-readable keys, so both outputs agree.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FARES, LOCATIONS, ROUTES, SOURCE, STOPS } from './demo-network.source.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function uuidFor(key) {
  const h = createHash('sha1').update(`trotch-demo:${key}`).digest('hex');
  // Format as an RFC 4122 v5-style UUID.
  const variant = ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${variant}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const sourceId = uuidFor(SOURCE.key);
const stopId = (k) => {
  if (!STOPS.some((s) => s[0] === k)) throw new Error(`Unknown stop key ${k}`);
  return uuidFor(`stop:${k}`);
};
const routeId = (k) => {
  if (!ROUTES.some((r) => r.key === k)) throw new Error(`Unknown route key ${k}`);
  return uuidFor(`route:${k}`);
};

const quality = (verification) => ({ verification, lastVerifiedAt: null, sourceId, isDemo: true });

const network = {
  sources: [{ id: sourceId, name: SOURCE.name, kind: SOURCE.kind, url: SOURCE.url, isDemo: true }],
  stops: STOPS.map(([key, cityId, name, kind, lat, lng, aliases, hint, verification]) => ({
    id: stopId(key), cityId, name, kind, lat, lng, aliases, landmarkHint: hint, isActive: true, quality: quality(verification),
  })),
  routes: ROUTES.map((r) => ({
    id: routeId(r.key), cityId: r.cityId, code: r.code, name: r.name, mode: r.mode, headsign: r.headsign,
    callOut: r.callOut, typicalWaitMin: r.typicalWaitMin,
    stops: r.stops.map(([k, m], i) => ({ stopId: stopId(k), minutesFromPrevious: i === 0 ? null : m })),
    path: null, isActive: true, notes: 'DEMO route for testing — not surveyed.', quality: quality('unverified'),
  })),
  fares: FARES.map(([key, rk, from, to, min, max, effFrom, effTo, verification]) => {
    const route = ROUTES.find((r) => r.key === rk);
    if (from) {
      const keys = route.stops.map((s) => s[0]);
      if (keys.indexOf(from) < 0 || keys.indexOf(to) <= keys.indexOf(from)) {
        throw new Error(`Fare ${key}: ${from}→${to} is not a forward segment of ${rk}`);
      }
    }
    return {
      id: uuidFor(`fare:${key}`), routeId: routeId(rk), fromStopId: from ? stopId(from) : null, toStopId: to ? stopId(to) : null,
      minGhs: min, maxGhs: max, effectiveFrom: effFrom, effectiveTo: effTo, quality: quality(verification),
    };
  }),
  locations: LOCATIONS.map(([key, cityId, name, kind, lat, lng, aliases, description]) => ({
    id: uuidFor(`location:${key}`), cityId, name, kind, lat, lng, aliases, description, isDemo: true,
  })),
};

// ---- JSON for the app -------------------------------------------------------
const jsonPath = resolve(root, 'src/data/demo-network.json');
mkdirSync(dirname(jsonPath), { recursive: true });
writeFileSync(jsonPath, JSON.stringify({ _notice: 'DEMO DATA — fictional/unverified, generated by scripts/generate-seed.mjs. Do not edit by hand.', ...network }, null, 2) + '\n');

// ---- SQL seed ---------------------------------------------------------------
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const lines = [];
lines.push('-- ============================================================================');
lines.push('-- TROTCH DEMO SEED — FICTIONAL / UNVERIFIED DATA FOR TESTING ONLY.');
lines.push('-- Generated by scripts/generate-seed.mjs from scripts/demo-network.source.mjs. Do not edit by hand.');
lines.push('-- Every row is flagged is_demo = true. Do not present as real-world transport information.');
lines.push('-- ============================================================================');
lines.push('');
lines.push("insert into public.cities (id, name, region) values ('accra', 'Accra', 'Greater Accra'), ('kumasi', 'Kumasi', 'Ashanti') on conflict (id) do nothing;");
lines.push('');
lines.push(`insert into public.data_sources (id, name, kind, url, notes, is_demo) values (${q(sourceId)}, ${q(SOURCE.name)}, 'demo', null, 'Illustrative data only. Replace with surveyed data before launch.', true) on conflict (id) do nothing;`);
lines.push('');
for (const s of network.stops) {
  lines.push(`insert into public.stops (id, city_id, name, kind, lat, lng, landmark_hint, verification_status, source_id, is_demo) values (${q(s.id)}, ${q(s.cityId)}, ${q(s.name)}, ${q(s.kind)}, ${s.lat}, ${s.lng}, ${q(s.landmarkHint)}, ${q(s.quality.verification)}, ${q(sourceId)}, true) on conflict (id) do nothing;`);
  for (const a of s.aliases) lines.push(`insert into public.stop_aliases (stop_id, alias) values (${q(s.id)}, ${q(a)}) on conflict do nothing;`);
}
lines.push('');
for (const l of network.locations) {
  lines.push(`insert into public.locations (id, city_id, name, kind, lat, lng, description, is_demo) values (${q(l.id)}, ${q(l.cityId)}, ${q(l.name)}, ${q(l.kind)}, ${l.lat}, ${l.lng}, ${q(l.description)}, true) on conflict (id) do nothing;`);
  for (const a of l.aliases) lines.push(`insert into public.location_aliases (location_id, alias) values (${q(l.id)}, ${q(a)}) on conflict do nothing;`);
}
lines.push('');
for (const r of network.routes) {
  lines.push(`insert into public.routes (id, city_id, code, name, mode, headsign, call_out, typical_wait_min, verification_status, source_id, notes, is_demo) values (${q(r.id)}, ${q(r.cityId)}, ${q(r.code)}, ${q(r.name)}, ${q(r.mode)}, ${q(r.headsign)}, ${q(r.callOut)}, ${q(r.typicalWaitMin)}, 'unverified', ${q(sourceId)}, ${q(r.notes)}, true) on conflict (id) do nothing;`);
  r.stops.forEach((rs, i) => {
    lines.push(`insert into public.route_stops (route_id, seq, stop_id, minutes_from_previous) values (${q(r.id)}, ${i}, ${q(rs.stopId)}, ${q(rs.minutesFromPrevious)}) on conflict do nothing;`);
  });
}
lines.push('');
for (const f of network.fares) {
  lines.push(`insert into public.fares (id, route_id, from_stop_id, to_stop_id, min_ghs, max_ghs, effective_from, effective_to, verification_status, source_id, is_demo) values (${q(f.id)}, ${q(f.routeId)}, ${q(f.fromStopId)}, ${q(f.toStopId)}, ${f.minGhs}, ${f.maxGhs}, ${q(f.effectiveFrom)}, ${q(f.effectiveTo)}, ${q(f.quality.verification)}, ${q(sourceId)}, true) on conflict (id) do nothing;`);
}
lines.push('');
writeFileSync(resolve(root, 'supabase/seed.sql'), lines.join('\n'));

console.log(`Generated ${network.stops.length} stops, ${network.routes.length} routes, ${network.fares.length} fares, ${network.locations.length} locations.`);
